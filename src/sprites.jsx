export function PixelSprite({
  art: artText,
  cell = 6,
  color = '#D96C8C',
  color2 = '#FFE9F0',
  palette,
  className = '',
  style,
}) {
  const rows = artText.trim().split('\n')
  const pick = (ch) => {
    if (palette) return palette[ch] ?? 'transparent'
    return ch === 'X' ? color : ch === 'H' ? color2 : 'transparent'
  }
  return (
    <span
      className={`pixel-sprite ${className}`}
      style={{ display: 'inline-flex', flexDirection: 'column', ...style }}
      aria-hidden="true"
    >
      {rows.map((row, y) => (
        <span key={y} style={{ display: 'inline-flex', lineHeight: 0 }}>
          {row.split('').map((ch, x) => (
            <span
              key={x}
              style={{
                width: cell,
                height: cell,
                background: pick(ch),
                display: 'inline-block',
              }}
            />
          ))}
        </span>
      ))}
    </span>
  )
}
